import { beforeEach, describe, expect, it, vi } from 'vitest';
import { act, fireEvent, screen, waitFor } from '@testing-library/react';
import { renderWithProviders } from '../helpers/render';
import { ApiError } from '@/lib/api/errors';
import { queryKeys } from '@/lib/api/queries';
import type { AssetDetail, AssetVersionPayload } from '@/lib/api/types';

const fetchApi = vi.hoisted(() => vi.fn());
const search = vi.hoisted(() => ({ value: '' }));
const push = vi.hoisted(() => vi.fn());

vi.mock('@/lib/api/client', () => ({ useAuthedFetch: () => fetchApi }));
vi.mock('@/lib/logger', () => ({
  logger: { warn: vi.fn(), info: vi.fn(), error: vi.fn(), debug: vi.fn() },
}));
vi.mock('next/navigation', () => ({
  useRouter: () => ({ push, replace: vi.fn(), back: vi.fn(), prefetch: vi.fn() }),
  usePathname: () => '/publish/a1',
  useSearchParams: () => new URLSearchParams(search.value),
}));

import { WizardProvider, useWizard } from '@/components/publish/wizard-context';
import { WizardHeader } from '@/components/publish/wizard-header';

const version = (over: Partial<AssetVersionPayload> & { id: string }): AssetVersionPayload => ({
  semver: '1.0.0',
  releaseNotes: null,
  publishedAt: '2026-01-01T00:00:00.000Z',
  isLatest: false,
  analysisStatus: 'READY',
  bytesTotal: '10',
  fileCount: 1,
  files: [{ id: `f-${over.id}`, relativePath: 'a.zip', kind: 'ARCHIVE', bytes: '10' }],
  compatibility: [{ engineVersion: '2022.3', renderPipelines: ['URP'], targets: ['WINDOWS'] }],
  dependencies: [],
  requiresEmptyProject: false,
  ...over,
});

const PUBLISHED = version({ id: 'v-pub', semver: '1.0.0', isLatest: true });
const DRAFT = version({ id: 'v-draft', semver: '1.1.0', publishedAt: null });
const EMPTY_DRAFT = version({
  id: 'v-empty',
  semver: '1.2.0',
  publishedAt: null,
  files: [],
  fileCount: 0,
  bytesTotal: '0',
});

const asset = (versions: AssetVersionPayload[], over: Partial<AssetDetail> = {}): AssetDetail => ({
  id: 'a1',
  slug: 'asset-one',
  title: 'Asset One',
  shortDescription: 's',
  longDescription: null,
  availableLocales: ['en'],
  engine: 'UNITY',
  category: { id: 'c', slug: 'c', name: 'C' },
  license: { id: 'l', slug: 'l', name: 'L' },
  tags: [],
  thumbnail: { key: 'k', url: '/t.webp' },
  thumbnailAutoGenerated: null,
  previewMedia: [],
  owner: {
    id: 'me',
    displayName: 'Me',
    avatar: { initials: 'M', bgColor: 'brand-blue', fgColor: 'ink-white' },
  },
  // the API sends versions by semver, newest first
  versions: [...versions].sort((a, b) => (a.semver < b.semver ? 1 : -1)),
  totalDownloads: 0,
  totalSaves: 0,
  status: 'PUBLISHED',
  publishedAt: '2026-01-01T00:00:00.000Z',
  updatedAt: '2026-01-01T00:00:00.000Z',
  createdAt: '2026-01-01T00:00:00.000Z',
  isSaved: false,
  canEdit: true,
  canDelete: true,
  canArchive: true,
  ...over,
});

function Probe() {
  const w = useWizard();
  return (
    <div>
      <span data-testid="version">{w.latestVersion?.id ?? 'none'}</span>
      <span data-testid="step">{w.step}</span>
      <span data-testid="files">{w.checklist.files.status}</span>
      <span data-testid="compat">{w.checklist.compatibility.status}</span>
    </div>
  );
}

const renderWizard = (a: AssetDetail, withHeader = false) => {
  fetchApi.mockResolvedValue(a);
  return renderWithProviders(
    <WizardProvider initialAsset={a} locale="en">
      <Probe />
      {withHeader ? <WizardHeader /> : null}
    </WizardProvider>,
  );
};

beforeEach(() => {
  fetchApi.mockReset();
  push.mockReset();
  search.value = '';
});

describe('WizardProvider working version', () => {
  it('without ?version it is the isLatest version', () => {
    renderWizard(asset([PUBLISHED, DRAFT]));
    expect(screen.getByTestId('version')).toHaveTextContent('v-pub');
    expect(screen.getByTestId('step')).toHaveTextContent('basics');
  });

  it('?version=<draft id> selects that version for the steps and the checklist, and opens Files', async () => {
    search.value = 'version=v-empty';
    renderWizard(asset([PUBLISHED, EMPTY_DRAFT]));
    expect(screen.getByTestId('version')).toHaveTextContent('v-empty');
    // the empty draft has no file even though the published latest has one
    expect(screen.getByTestId('files')).toHaveTextContent('pending');
    await waitFor(() => expect(screen.getByTestId('step')).toHaveTextContent('files'));
  });

  it('an unknown ?version keeps the isLatest rule', () => {
    search.value = 'version=v-nope';
    renderWizard(asset([PUBLISHED, DRAFT]));
    expect(screen.getByTestId('version')).toHaveTextContent('v-pub');
    expect(screen.getByTestId('step')).toHaveTextContent('basics');
  });

  it('picks the draft up once it shows in the asset (refetch after creation)', async () => {
    search.value = 'version=v-draft';
    const { client } = renderWizard(asset([PUBLISHED]));
    expect(screen.getByTestId('version')).toHaveTextContent('v-pub');
    expect(screen.getByTestId('step')).toHaveTextContent('basics');
    act(() => {
      client.setQueryData(queryKeys.asset('a1', 'en'), asset([PUBLISHED, DRAFT]));
    });
    await waitFor(() => expect(screen.getByTestId('version')).toHaveTextContent('v-draft'));
    await waitFor(() => expect(screen.getByTestId('step')).toHaveTextContent('files'));
  });
});

describe('WizardHeader publish target and error mapping', () => {
  it('publishes the draft working version through the version endpoint (flips isLatest)', async () => {
    search.value = 'version=v-draft';
    renderWizard(asset([PUBLISHED, DRAFT]), true);
    fetchApi.mockClear();
    fetchApi.mockResolvedValue(undefined);
    fireEvent.click(screen.getByRole('button', { name: 'publish.updateCta' }));
    await waitFor(() =>
      expect(fetchApi).toHaveBeenCalledWith('/assets/a1/versions/v-draft/publish', {
        method: 'POST',
        body: {},
      }),
    );
    await waitFor(() => expect(push).toHaveBeenCalledWith('/assets/asset-one'));
  });

  it('without ?version it publishes the asset, as before', async () => {
    renderWizard(asset([PUBLISHED, DRAFT]), true);
    fetchApi.mockClear();
    fetchApi.mockResolvedValue({ warnings: [] });
    fireEvent.click(screen.getByRole('button', { name: 'publish.updateCta' }));
    await waitFor(() =>
      expect(fetchApi).toHaveBeenCalledWith('/assets/a1/publish', { method: 'POST', body: {} }),
    );
  });

  it('a blocked publish jumps to the step named by the field path, including version.* paths', async () => {
    for (const [path, step] of [
      ['version.compatibility', 'compatibility'],
      ['version.files', 'files'],
      ['thumbnail', 'media'],
      ['license', 'license'],
    ] as const) {
      const { unmount } = renderWizard(asset([PUBLISHED]), true);
      fetchApi.mockClear();
      fetchApi.mockRejectedValue(
        new ApiError({
          type: 'about:blank',
          title: 'Bad Request',
          status: 400,
          code: 'asset.publish_blocked',
          fields: [{ path, code: 'x', message: 'm' }],
        }),
      );
      fireEvent.click(screen.getByRole('button', { name: 'publish.updateCta' }));
      await waitFor(() => expect(screen.getByTestId('step')).toHaveTextContent(step));
      unmount();
    }
  });
});
