import { describe, expect, it } from 'vitest';
import { fixtureAsset, FX_PERSONA } from '@/preview/test-utils';
import {
  evaluateChecklist,
  newestCreated,
  SEMVER_REGEX,
  toProblemFields,
} from '@/preview/handlers/publish-checklist';
import type { AssetRecord, AssetVersionRecord } from '@/preview/records';

const draft = (over: Partial<AssetRecord> = {}): AssetRecord =>
  fixtureAsset('a-d', { status: 'DRAFT', ownerId: FX_PERSONA, ...over });

const version = (over: Partial<AssetVersionRecord> = {}): AssetVersionRecord => ({
  ...draft().versions[0]!,
  ...over,
});

const codes = (a: AssetRecord, versions?: AssetVersionRecord[]) =>
  evaluateChecklist(a, versions).errors.map((v) => `${v.field}:${v.code}`);

describe('evaluateChecklist', () => {
  it('passes for a complete draft', () => {
    const r = evaluateChecklist(draft());
    expect(r).toEqual({ ok: true, violations: [], errors: [], warnings: [] });
  });

  it('flags a missing thumbnail (key, url and auto-generated all empty)', () => {
    const a = draft({ thumbnail: { key: null, url: null } });
    expect(codes(a)).toEqual(['thumbnail:thumbnail.missing']);
  });

  it('accepts an auto-generated thumbnail', () => {
    const a = draft({
      thumbnail: { key: null, url: null },
      thumbnailAutoGenerated: { key: 'k', url: '/auto.webp' },
    });
    expect(evaluateChecklist(a).ok).toBe(true);
  });

  it('flags a missing license and category', () => {
    expect(codes(draft({ licenseId: '', categoryId: '' }))).toEqual([
      'license:license.missing',
      'category:category.missing',
    ]);
  });

  it('flags missing translations (no available locale)', () => {
    expect(codes(draft({ availableLocales: [] }))).toEqual(['translations:translations.empty']);
  });

  it('flags a blank title', () => {
    expect(codes(draft({ title: '   ' }))).toEqual(['title:title.missing']);
  });

  it('flags a missing version and stops there', () => {
    const a = draft({ versions: [], thumbnail: { key: null, url: null } });
    expect(codes(a)).toEqual(['thumbnail:thumbnail.missing', 'version:version.missing']);
  });

  it('flags an invalid semver on the newest version', () => {
    const a = draft({ versions: [version({ semver: '1.0.0-beta' })] });
    expect(codes(a)).toEqual(['version.semver:semver.invalid']);
  });

  it('flags a latest version without files', () => {
    const a = draft({ versions: [version({ files: [], fileCount: 0, bytesTotal: '0' })] });
    expect(codes(a)).toEqual(['version.files:version.empty']);
  });

  // Deviation from the backend (which blocks on any non-READY status): the wizard says the
  // analyzer no longer gates Publish, and the 2 s simulated analysis would otherwise block a
  // publish started right after an upload without any explanation. Only FAILED blocks.
  it('an analysis that is still running is a warning, not a blocker', () => {
    for (const s of ['PENDING', 'ANALYZING'] as const) {
      const a = draft({ versions: [version({ analysisStatus: s })] });
      const r = evaluateChecklist(a);
      expect(r.ok, s).toBe(true);
      expect(r.errors, s).toEqual([]);
      expect(
        r.warnings.map((v) => `${v.field}:${v.code}:${v.severity}`),
        s,
      ).toEqual(['version.analysis:analysis.incomplete:warning']);
    }
  });

  it('a FAILED analysis blocks', () => {
    const a = draft({ versions: [version({ analysisStatus: 'FAILED' })] });
    const r = evaluateChecklist(a);
    expect(r.ok).toBe(false);
    expect(codes(a)).toEqual(['version.analysis:analysis.failed']);
  });

  it('requires compatibility unless the engine is ENGINE_AGNOSTIC', () => {
    const noCompat = version({ compatibility: [] });
    expect(codes(draft({ engine: 'UNITY', versions: [noCompat] }))).toEqual([
      'version.compatibility:compatibility.missing',
    ]);
    expect(evaluateChecklist(draft({ engine: 'ENGINE_AGNOSTIC', versions: [noCompat] })).ok).toBe(
      true,
    );
  });

  it('reports several failures at once, in the backend order', () => {
    const a = draft({
      thumbnail: { key: null, url: null },
      licenseId: '',
      versions: [
        version({ files: [], fileCount: 0, compatibility: [], analysisStatus: 'PENDING' }),
      ],
    });
    expect(codes(a)).toEqual([
      'thumbnail:thumbnail.missing',
      'license:license.missing',
      'version.files:version.empty',
      'version.compatibility:compatibility.missing',
    ]);
    expect(evaluateChecklist(a).warnings.map((v) => v.code)).toEqual(['analysis.incomplete']);
  });

  it('evaluates the NEWEST created version, not the isLatest one', () => {
    const published = version({ id: 'v1', semver: '1.0.0', createdAt: '2026-01-01T00:00:00.000Z' });
    const newer = version({
      id: 'v2',
      semver: '1.1.0',
      isLatest: false,
      createdAt: '2026-02-01T00:00:00.000Z',
      files: [],
      fileCount: 0,
    });
    expect(codes(draft({ versions: [published, newer] }))).toEqual(['version.files:version.empty']);
  });

  it('uses the explicit versions argument', () => {
    const a = draft();
    expect(codes(a, [version({ files: [], fileCount: 0 })])).toEqual([
      'version.files:version.empty',
    ]);
  });

  it('toProblemFields maps to the { path, code, message } wire shape', () => {
    const r = evaluateChecklist(draft({ thumbnail: { key: null, url: null } }));
    expect(toProblemFields(r.errors)).toEqual([
      {
        path: 'thumbnail',
        code: 'thumbnail.missing',
        message: 'Upload a thumbnail before publishing.',
      },
    ]);
  });
});

describe('newestCreated', () => {
  it('breaks createdAt ties by position (later wins) and handles empty', () => {
    const a = version({ id: 'a', createdAt: '2026-01-01T00:00:00.000Z' });
    const b = version({ id: 'b', createdAt: '2026-01-01T00:00:00.000Z' });
    const c = version({ id: 'c', createdAt: '2025-12-01T00:00:00.000Z' });
    expect(newestCreated([a, b, c])?.id).toBe('b');
    expect(newestCreated([])).toBeUndefined();
  });
});

describe('SEMVER_REGEX', () => {
  it('is strict MAJOR.MINOR.PATCH', () => {
    expect(SEMVER_REGEX.test('1.2.3')).toBe(true);
    expect(SEMVER_REGEX.test('10.0.12')).toBe(true);
    for (const bad of ['1.2', '1.2.3.4', 'v1.2.3', '1.2.3-beta', '', ' 1.2.3']) {
      expect(SEMVER_REGEX.test(bad)).toBe(false);
    }
  });
});
