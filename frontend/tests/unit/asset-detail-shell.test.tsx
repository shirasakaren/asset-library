  previewMedia: [],
  owner: {
    id: 'owner-1',
    displayName: 'Someone Else',
    avatar: { initials: 'SE', bgColor: 'brand-blue', fgColor: 'ink-white' },
  },
  versions: [],
  totalDownloads: 0,
  totalSaves: 0,
  status: 'PUBLISHED',
