/**
 * Generates THIRD_PARTY_NOTICES.md (repository root) from scripts/seed/assets.yaml and
 * public/thumbs/manifest.json. Deterministic: no dates, stable sort, LF line endings.
 *
 *   tsx scripts/seed/notices.ts [--out <file>]
 *
 * `pnpm seed:notices` regenerates the committed file; a unit test regenerates it to a temp path
 * and compares, so it cannot go stale.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';

interface Entry {
  slug: string;
  title: string;
  store: string;
  url: string;
  image: string;
}
interface ManifestRow {
  sourceImage: string;
  sourcePage: string;
  store: string;
}

const ROOT = path.resolve(__dirname, '../..');
const REPO_ROOT = path.resolve(ROOT, '..');
const TAKEDOWN = 'it@labmgm.org';

const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const link = (u: string): string =>
  `<${u.replace(/\|/g, '%7C').replace(/[<>\s]/g, encodeURIComponent)}>`;

/** The full text of the notices file for the given catalog and manifest. */
export function renderNotices(entries: Entry[], manifest: Record<string, ManifestRow>): string {
  const rows = entries.map((e) => {
    const m = manifest[e.slug];
    return {
      store: m?.store ?? e.store,
      title: e.title,
      slug: e.slug,
      page: m?.sourcePage ?? e.url,
      image: m?.sourceImage ?? e.image,
    };
  });
  rows.sort((a, b) => cmp(a.store, b.store) || cmp(a.title, b.title) || cmp(a.slug, b.slug));
  const stores = [...new Set(rows.map((r) => r.store))];

  const out: string[] = [];
  out.push(
    '# Third-party notices',
    '',
    '<!-- Generated by `pnpm seed:notices` (frontend/scripts/seed/notices.ts) from',
    '     frontend/scripts/seed/assets.yaml and frontend/public/thumbs/manifest.json. Do not edit by hand. -->',
    '',
    '## Listing thumbnails and titles',
    '',
    `The demo catalog shows ${rows.length} real listings from public asset stores. Their thumbnails (\`frontend/public/thumbs\`, downsized copies of each listing's own image) and their titles are third-party material owned by their respective creators and stores. They are bundled only to demonstrate the product, they are **not** covered by this repository's license, and every asset page links back to the original listing.`,
    '',
    `To request the removal of a listing or thumbnail, contact [${TAKEDOWN}](mailto:${TAKEDOWN}).`,
    '',
    '## Fonts',
    '',
    'The latin subsets of these variable fonts are self-hosted in `frontend/src/styles/fonts` (obtained from Google Fonts) and are licensed under the [SIL Open Font License 1.1](https://openfontlicense.org):',
    '',
    '- Bricolage Grotesque, Copyright The Bricolage Grotesque Project Authors (<https://github.com/ateliertriay/bricolage>)',
    '- Geist and Geist Mono, Copyright Vercel, in collaboration with basement.studio (<https://github.com/vercel/geist-font>)',
    '',
    '## Listings',
    '',
    `${rows.length} listings from ${stores.length} sources, grouped by store and sorted by title.`,
    '',
  );
  for (const store of stores) {
    const group = rows.filter((r) => r.store === store);
    out.push(
      `### ${cell(store)} (${group.length})`,
      '',
      '| Title | Original page | Image source |',
      '| --- | --- | --- |',
      ...group.map((r) => `| ${cell(r.title)} | ${link(r.page)} | ${link(r.image)} |`),
      '',
    );
  }
  return out.join('\n');
}

function main(): void {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--out');
  const target =
    i >= 0 && argv[i + 1]
      ? path.resolve(argv[i + 1]!)
      : path.join(REPO_ROOT, 'THIRD_PARTY_NOTICES.md');
  const entries = parse(fs.readFileSync(path.join(__dirname, 'assets.yaml'), 'utf8')) as Entry[];
  const manifest = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'public/thumbs/manifest.json'), 'utf8'),
  ) as Record<string, ManifestRow>;
  const text = renderNotices(entries, manifest);
  fs.writeFileSync(target, text);
  console.log(`${path.relative(process.cwd(), target) || target}: ${entries.length} listings`);
}

// Only when run as a script (the unit test imports renderNotices).
if (require.main === module) main();
