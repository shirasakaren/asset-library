const MISSING_USER = 'Unknown user';
const STATUSES: readonly AssetStatus[] = ['DRAFT', 'PUBLISHED', 'ARCHIVED', 'DELETED'];

/** An asset by id or slug in any status (DELETED included; id wins), or a 404. */
export function findAnyAsset(assets: AssetRecord[], idOrSlug: string): AssetRecord {
  const asset = assets.find((a) => a.id === idOrSlug) ?? assets.find((a) => a.slug === idOrSlug);
  if (!asset) throw notFound(`Asset ${idOrSlug} not found.`, { code: 'asset.not_found' });
  return asset;
}

/** A live (not DELETED) asset by id or slug, or a 404. */
export function findLiveAsset(assets: AssetRecord[], idOrSlug: string): AssetRecord {
  const asset = findAsset(assets, idOrSlug);
  if (!asset) throw notFound(`Asset ${idOrSlug} not found.`, { code: 'asset.not_found' });
  return asset;
}

export function toAdminRow(a: AssetRecord, maps: CatalogMaps, locale: LocaleCode): AdminAssetRow {
  const owner = maps.users.get(a.ownerId);
  return {
    id: a.id,
    slug: a.slug,
    title: localizedName(a.titleI18n, locale) || a.title,
    ownerId: a.ownerId,
    ownerDisplayName: owner?.displayName ?? MISSING_USER,
    ownerEmail: owner?.email,
    engine: a.engine,
    status: a.status,
    thumbnailUrl: a.thumbnail?.url ?? a.thumbnailAutoGenerated?.url ?? null,
    categoryName: localizedName(maps.categories.get(a.categoryId)?.name, locale),
    totalDownloads: a.totalDownloads,
    totalSaves: a.totalSaves,
    updatedAt: a.updatedAt,
    publishedAt: a.publishedAt,
  };
}

/** `q` matches title, slug, id, owner name or email (contains) or the catalog search tokenizer. */
function matchesQuery(a: AssetRecord, q: string, maps: CatalogMaps): boolean {
  const needle = normalize(q.trim());
  if (!needle) return true;
  const owner = maps.users.get(a.ownerId);
  const hay = [a.title, a.titleI18n?.en, a.slug, a.id, owner?.displayName, owner?.email];
  if (hay.some((h) => h && normalize(h).includes(needle))) return true;
  return scoreAsset(a, parseQuery(q), maps) > 0;
}

/**
 * Cross-status asset list for the admin tables: every asset but DELETED unless `status` asks for
 * it (`status=DELETED` is the page's "Deleted" chip). Filters: `status` (one or many), `ownerId`,
 * `categoryId` / `categoryIds`, `engine`, `q`; `sort` as the catalog (default `recentlyUpdated`,
 * the page's default); cursor pages. `counts` are the global status counts (not filtered), which
 * the page shows on its chips (the backend sends them as `X-Total-*` headers).
 */
adminRoute('GET', '/admin/assets', async (req, ctx): Promise<AdminAssetListPage> => {
  const locale = reqLocale(req);
  const sort = parseSort(req.query.get('sort')) ?? 'recentlyUpdated';
  const query = new URLSearchParams(req.query);
  const single = query.get('categoryId');
  if (single) query.append('categoryIds', single);
  const filters = parseAssetFilters(query);
  const statuses = parseStatuses(query);
  const [maps, all] = await Promise.all([loadCatalogMaps(ctx), ctx.db.list<AssetRecord>('assets')]);

  const counts = Object.fromEntries(STATUSES.map((s) => [s, 0])) as Record<AssetStatus, number>;
  for (const a of all) counts[a.status] += 1;

  const scope = all.filter((a) =>
    statuses.length > 0 ? statuses.includes(a.status) : a.status !== 'DELETED',
  );
  const matching = filterAssets(scope, filters, maps).filter((a) =>
    matchesQuery(a, filters.q, maps),
  );
  const page = paginate(sortAssets(matching, sort), req.query);
  return {
    items: page.items.map((a) => toAdminRow(a, maps, locale)),
    pageInfo: page.pageInfo,
    counts,
  };
});

/** Admin detail: any status, including DELETED. */
adminRoute('GET', '/admin/assets/{id}', async (req, ctx): Promise<AssetDetail> => {
  const asset = findAnyAsset(await ctx.db.list<AssetRecord>('assets'), req.params.id!);
  return toDetail(asset, ctx, reqLocale(req));
});

/**
 * Edit on behalf of the owner: the owner path's validation and writes (`applyAssetUpdate`), plus an
 * optional `reason` (4..500 characters). One `asset.admin_edit` audit row `{ fields, reason? }` when
 * something changed.
 */
adminRoute('PATCH', '/admin/assets/{id}', (req, ctx) => {
  const reason = parseReason(req.body, { required: false });
  return serialized(async () => {
    const { writable, changed } = await applyAssetUpdate(ctx, req.params.id!, req.body);
    if (changed.length > 0) {
      await recordAudit(ctx, {
        action: 'asset.admin_edit',
        subjectType: 'Asset',
        subjectId: writable.asset.id,
        metadata: reason ? { fields: changed, reason } : { fields: changed },
      });
    }
    return undefined;
  });
});

/** Admin archive: a reason is mandatory; PUBLISHED assets only (`asset.archive_blocked` otherwise). */
adminRoute('POST', '/admin/assets/{id}/archive', (req, ctx) => {
  const reason = parseReason(req.body, { required: true });
  return serialized(async () => {
    const asset = findLiveAsset(await ctx.db.list<AssetRecord>('assets'), req.params.id!);
    await archiveAsset(ctx, asset);
    await recordAudit(ctx, {
      action: 'asset.admin_archive',
      subjectType: 'Asset',
      subjectId: asset.id,
      metadata: { previousStatus: asset.status, reason },
    });
    return undefined;
  });
});

/** Restores an ARCHIVED or soft-deleted asset (see `restoreAsset`). */
adminRoute('POST', '/admin/assets/{id}/restore', (req, ctx) =>
  serialized(async () => {
    const asset = findAnyAsset(await ctx.db.list<AssetRecord>('assets'), req.params.id!);
    await restoreAsset(ctx, asset, { allowDeleted: true });
    await recordAudit(ctx, {
      action: 'asset.admin_restore',
      subjectType: 'Asset',
      subjectId: asset.id,
      metadata: { previousStatus: asset.status },
    });
    return undefined;
  }),
);

/** Admin soft delete: a reason is mandatory; the asset is hidden everywhere (status DELETED). */
adminRoute('DELETE', '/admin/assets/{id}', (req, ctx) => {
  const reason = parseReason(req.body, { required: true });
  return serialized(async () => {
    const asset = findLiveAsset(await ctx.db.list<AssetRecord>('assets'), req.params.id!);
    await softDeleteAsset(ctx, asset);
    await recordAudit(ctx, {
      action: 'asset.admin_delete',
      subjectType: 'Asset',
      subjectId: asset.id,
      metadata: { previousStatus: asset.status, reason },
    });
    return undefined;
  });
});
