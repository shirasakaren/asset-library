import type { AssetRecord, AssetVersionRecord } from '../records';

/** Same regex as the backend DTO (`SEMVER_REGEX`). */
export const SEMVER_REGEX = /^\d+\.\d+\.\d+$/;

export interface Violation {
  /** Dotted path the wizard maps to a step (`thumbnail`, `version.files`, ...). */
  field: string;
  code: string;
  message: string;
  /** Warnings could be confirmed through; the backend produces none today. */
  severity: 'error' | 'warning';
}

export interface ChecklistResult {
  ok: boolean;
  violations: Violation[];
  errors: Violation[];
  warnings: Violation[];
}

/**
 * The version a publish evaluates and publishes: the most recently CREATED one (the backend
 * orders by `createdAt desc`). Ties within the same second go to the one added last, because
 * `versions` is stored oldest first.
 */
export function newestCreated(versions: AssetVersionRecord[]): AssetVersionRecord | undefined {
  let best: AssetVersionRecord | undefined;
  for (const v of versions) if (!best || v.createdAt >= best.createdAt) best = v;
  return best;
}

const error = (field: string, code: string, message: string): Violation => ({
  field,
  code,
  message,
  severity: 'error',
});

/**
 * Port of `PublishChecklistService.evaluate`, over a stored asset instead of Prisma rows.
 * Order and `code`/`field` values are the backend's, because `wizard-header.tsx` reads
 * `fields[0].path` (`thumbnail*`, `files*` / `version.files*`, `compatibility*`, `license*`) to jump
 * to a step, and tests assert the codes. Differences:
 *  - a blank title is also reported (the wizard cannot produce one);
 *  - an auto-generated thumbnail counts, like the wizard's own checklist (the backend only
 *    looks at `thumbnailKey`);
 *  - a running analysis (PENDING / ANALYZING) is a warning, not an error (see below);
 *  - "has a translation" is `availableLocales.length > 0` (the stored equivalent).
 */
export function evaluateChecklist(
  asset: AssetRecord,
  versions: AssetVersionRecord[] = asset.versions,
): ChecklistResult {
  const violations: Violation[] = [];

  if (!asset.title.trim()) {
    violations.push(error('title', 'title.missing', 'Give the asset a title.'));
  }
  if (!(asset.thumbnail?.key || asset.thumbnail?.url || asset.thumbnailAutoGenerated?.url)) {
    violations.push(
      error('thumbnail', 'thumbnail.missing', 'Upload a thumbnail before publishing.'),
    );
  }
  if (!asset.licenseId) {
    violations.push(error('license', 'license.missing', 'Select a license.'));
  }
  if (!asset.categoryId) {
    violations.push(error('category', 'category.missing', 'Select a category.'));
  }
  if (asset.availableLocales.length === 0) {
    violations.push(
      error('translations', 'translations.empty', 'Provide at least one localized description.'),
    );
  }

  const latest = newestCreated(versions);
  if (!latest) {
    violations.push(error('version', 'version.missing', 'Create at least one version.'));
  } else {
    if (!SEMVER_REGEX.test(latest.semver)) {
      violations.push(
        error(
          'version.semver',
          'semver.invalid',
          `Version ${latest.semver} is not valid semver (MAJOR.MINOR.PATCH).`,
        ),
      );
    }
    if (latest.files.length === 0) {
      violations.push(
        error('version.files', 'version.empty', 'Upload at least one file in the latest version.'),
      );
    }
    // Deviation: the backend blocks on any status other than READY. The wizard states that the
    // analyzer does not gate Publish, and the simulated analysis (2 s after an upload) would
    // otherwise block a publish started right after uploading with no explanation. A running
    // analysis is therefore a warning; only a FAILED one blocks.
    if (latest.analysisStatus === 'FAILED') {
      violations.push(
        error('version.analysis', 'analysis.failed', 'The analyzer failed on the latest version.'),
      );
    } else if (latest.analysisStatus !== 'READY') {
      violations.push({
        field: 'version.analysis',
        code: 'analysis.incomplete',
        message: 'The analyzer has not finished processing the latest version.',
        severity: 'warning',
      });
    }
    if (asset.engine !== 'ENGINE_AGNOSTIC' && latest.compatibility.length === 0) {
      violations.push(
        error(
          'version.compatibility',
          'compatibility.missing',
          'Declare at least one engine/version/target combination.',
        ),
      );
    }
  }

  const errors = violations.filter((v) => v.severity === 'error');
  return {
    ok: errors.length === 0,
    violations,
    errors,
    warnings: violations.filter((v) => v.severity === 'warning'),
  };
}

/** The `ProblemDetail.fields` entries of the `asset.publish_blocked` response. */
export const toProblemFields = (violations: Violation[]) =>
  violations.map((v) => ({ path: v.field, code: v.code, message: v.message }));
