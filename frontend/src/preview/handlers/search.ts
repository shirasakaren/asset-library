import type { SearchAssetHit, SearchAssetsResponse, Tag } from '@/lib/api/types';
import type { AssetRecord, TagRecord } from '../records';
import { route } from '../router/router';
import { filterAssets, parseAssetFilters } from './filters';
import {
  intParam,
  loadCatalogMaps,
  localizedName,
  parseSort,
  reqLocale,
  sortAssets,
} from './helpers';
import { parseQuery, rankTags, scoreAsset } from './text-search';

/**
 * Typeahead / search endpoint. Only PUBLISHED assets; same filters as `GET /assets`.
 * Non-empty `q`: tokenized AND match, ranked by score, then downloads, then id. Empty `q`:
 * browse order (`sort`, newest by default). `limit`/`offset` windows the ranked list and
 * `estimatedTotalHits` is the full match count. Facets are not part of the response type.
 */
route('GET', '/search/assets', async (req, ctx): Promise<SearchAssetsResponse> => {
  const locale = reqLocale(req);
  const limit = intParam(req.query, 'limit', { def: 24, min: 1, max: 100 });
  const offset = intParam(req.query, 'offset', { def: 0, min: 0, max: Number.MAX_SAFE_INTEGER });
  const sort = parseSort(req.query.get('sort'));
  const filters = parseAssetFilters(req.query);
  const [maps, all] = await Promise.all([loadCatalogMaps(ctx), ctx.db.list<AssetRecord>('assets')]);

  const candidates = filterAssets(
    all.filter((a) => a.status === 'PUBLISHED'),
    filters,
    maps,
  );
  const parsed = parseQuery(filters.q);
  let ranked: AssetRecord[];
  if (parsed.tokens.length > 0) {
    const scores = new Map<string, number>();
    for (const a of candidates) {
      const s = scoreAsset(a, parsed, maps);
      if (s > 0) scores.set(a.id, s);
    }
    ranked = candidates
      .filter((a) => scores.has(a.id))
      .sort(
        (a, b) =>
          scores.get(b.id)! - scores.get(a.id)! ||
          b.totalDownloads - a.totalDownloads ||
          (a.id < b.id ? -1 : 1),
      );
  } else {
    ranked = sortAssets(candidates, sort ?? 'newest');
  }

  const hits = ranked.slice(offset, offset + limit).map((a): SearchAssetHit => ({
    id: a.id,
    slug: a.slug,
    title: localizedName(a.titleI18n, locale) || a.title,
    shortDescription: localizedName(a.shortDescriptionI18n, locale) || a.shortDescription,
    thumbnailUrl: a.thumbnail?.url ?? a.thumbnailAutoGenerated?.url ?? null,
    engine: a.engine,
    categoryName: localizedName(maps.categories.get(a.categoryId)?.name, locale),
    ownerName: maps.users.get(a.ownerId)?.displayName ?? '',
    totalDownloads: a.totalDownloads,
  }));

  return {
    hits,
    // Small deterministic stand-in for the search engine's timing.
    processingTimeMs: 1 + (filters.q.length % 3),
    estimatedTotalHits: ranked.length,
  };
});

/** Tag typeahead: `Tag[]`, names/slugs starting with `q` first, then containing it. Empty `q` => []. */
route('GET', '/search/tags', async (req, ctx): Promise<Tag[]> => {
  const limit = intParam(req.query, 'limit', { def: 8, min: 1, max: 20 });
  const q = (req.query.get('q') ?? '').trim();
  if (!q) return [];
  const tags = await ctx.db.list<TagRecord>('tags');
  return rankTags(tags, q, 'search')
    .slice(0, limit)
    .map((t) => ({ id: t.id, slug: t.slug, displayName: t.displayName, usageCount: t.usageCount }));
});
