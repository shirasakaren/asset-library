import type {
  AssetRecord,
  AssetVersionRecord,
  CategoryRecord,
  LicenseRecord,
  TagRecord,
} from '../records';
import { route, type PreviewContext } from '../router/router';
import { badRequest, notFound } from '../router/errors';
import { parseCreate } from './asset-input';
import { applyAssetUpdate } from './asset-update';
import {
  archiveAsset,
  auditAdminAction,
  auditAdminEdit,
  restoreAsset,
  softDeleteAsset,
} from './asset-lifecycle';
import {
  applyTranslations,
  commitTags,
  isoSeconds,
  loadWritable,
  planTags,
  slugifyTitle,
  takenSlugs,
  uniqueSlug,
} from './asset-write-core';
import { evaluateChecklist, newestCreated, toProblemFields } from './publish-checklist';
import { markLatest } from './version-core';
import { serialized } from './write-queue';

const changed = (ctx: PreviewContext) => ctx.emit({ type: 'assets.changed' });

const blocked = (message: string) => badRequest(message, { code: 'asset.publish_blocked' });

/**
 * Create a DRAFT owned by the persona with its first version (analysis PENDING until a file is
 * attached). Responds `{ id, slug }`, which `publish/new/page.tsx` uses to open the wizard.
 * The slug comes from the title once; `-2`, `-3` ... resolve collisions.
 */
route('POST', '/assets', (req, ctx) =>
  serialized(async () => {
    const input = parseCreate(req.body);
    const [category, license, assets, tags] = await Promise.all([
      ctx.db.get<CategoryRecord>('categories', input.categoryId),
      ctx.db.get<LicenseRecord>('licenses', input.licenseId),
      ctx.db.list<AssetRecord>('assets'),
      ctx.db.list<TagRecord>('tags'),
    ]);
    if (!category) {
      throw notFound(`Category ${input.categoryId} not found.`, { code: 'category.not_found' });
    }
    if (!license) {
      throw notFound(`License ${input.licenseId} not found.`, { code: 'license.not_found' });
    }

    const now = isoSeconds(ctx);
    const plan = planTags(ctx, input.tags, tags, now);
    const slug = uniqueSlug(slugifyTitle(input.title), takenSlugs(assets));
    const version: AssetVersionRecord = {
      id: ctx.newId('v'),
      semver: input.semver,
      releaseNotes: null,
      publishedAt: null,
      isLatest: true,
      analysisStatus: 'PENDING',
      bytesTotal: '0',
      fileCount: 0,
      files: [],
      compatibility: [],
      dependencies: [],
      requiresEmptyProject: input.requiresEmptyProject,
      createdAt: now,
      avStatus: 'CLEAN',
      avAcknowledgedAt: null,
    };
    const asset: AssetRecord = {
      id: ctx.newId('a-new'),
      slug,
      title: input.title,
      engine: input.engine,
      thumbnail: { key: null, url: null },
      thumbnailAutoGenerated: null,
      previewMedia: [],
      totalDownloads: 0,
      totalSaves: 0,
      status: 'DRAFT',
      publishedAt: null,
      updatedAt: now,
      createdAt: now,
      ownerId: ctx.meId,
      categoryId: input.categoryId,
      licenseId: input.licenseId,
      tagIds: plan.tagIds,
      titleI18n: { en: input.title, id: input.title },
      thumbnailSmall: null,
      // Runtime-created assets have no store listing.
      storeName: '',
      storeUrl: '',
      viewCount: 0,
      versions: [version],
      ...applyTranslations(
        {
          shortDescription: '',
          longDescription: null,
          shortDescriptionI18n: { en: '', id: '' },
          availableLocales: [],
        },
        input.translations,
      ),
    };
    await commitTags(ctx, plan, []);
    await ctx.db.put<AssetRecord>('assets', asset);
    changed(ctx);
    return { id: asset.id, slug };
  }),
);

/** Partial update (see `applyAssetUpdate`). An admin editing another owner's asset is audited. */
route('PATCH', '/assets/{id}', (req, ctx) =>
  serialized(async () => {
    const { writable, changed: fields } = await applyAssetUpdate(ctx, req.params.id!, req.body);
    await auditAdminEdit(ctx, writable, fields);
    return undefined;
  }),
);

/** Soft delete: status DELETED (404 everywhere), tag usage released. Owner or admin. */
route('DELETE', '/assets/{id}', (req, ctx) =>
  serialized(async () => {
    const w = await loadWritable(ctx, req.params.id!);
    await softDeleteAsset(ctx, w.asset);
    await auditAdminAction(ctx, w, 'asset.admin_delete', { previousStatus: w.asset.status });
    return undefined;
  }),
);

/**
 * Runs the publish checklist (`asset.publish_blocked` with `fields: [{ path, code, message }]`
 * when it fails; the wizard reads `fields[0].path` to pick the step) and then publishes: the
 * asset becomes PUBLISHED (`publishedAt` is kept when it already was) and the newest created
 * version is published too, becoming the single `isLatest` one. Also serves "Update" on an
 * already published asset.
 */
route('POST', '/assets/{id}/publish', (req, ctx) =>
  serialized(async () => {
    const { asset } = await loadWritable(ctx, req.params.id!);
    if (asset.status === 'ARCHIVED') throw blocked('Restore the asset before publishing it.');
    const result = evaluateChecklist(asset);
    if (result.errors.length > 0) {
      throw badRequest('Publish blocked by checklist failures.', {
        code: 'asset.publish_blocked',
        fields: toProblemFields(result.errors),
      });
    }

    const now = isoSeconds(ctx);
    const target = newestCreated(asset.versions);
    const patch: Partial<AssetRecord> = { status: 'PUBLISHED', updatedAt: now };
    if (asset.status !== 'PUBLISHED') patch.publishedAt = now;
    if (target && !target.publishedAt) patch.versions = markLatest(asset.versions, target.id, now);
    await ctx.db.patch<AssetRecord>('assets', asset.id, patch);
    changed(ctx);
    return { warnings: toProblemFields(result.warnings) };
  }),
);

route('POST', '/assets/{id}/archive', (req, ctx) =>
  serialized(async () => {
    const w = await loadWritable(ctx, req.params.id!);
    await archiveAsset(ctx, w.asset);
    await auditAdminAction(ctx, w, 'asset.admin_archive', { previousStatus: w.asset.status });
    return undefined;
  }),
);

route('POST', '/assets/{id}/restore', (req, ctx) =>
  serialized(async () => {
    const w = await loadWritable(ctx, req.params.id!);
    await restoreAsset(ctx, w.asset);
    await auditAdminAction(ctx, w, 'asset.admin_restore', { previousStatus: w.asset.status });
    return undefined;
  }),
);
